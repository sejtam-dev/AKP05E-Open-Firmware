#!/usr/bin/env python3
"""Generate firmware/app/font5x7.h (the 5x7 pixel font of the boot screen banner) from the glyph drawings below.

    python scripts\\maintenance\\gen_font5x7.py          # rewrites firmware/app/font5x7.h
    python scripts\\maintenance\\gen_font5x7.py --show   # prints every glyph as ASCII art

The glyphs are drawn here (original work, no third-party font data). Only the characters the banner needs exist;
lower case letters are drawn as upper case by the renderer in display.c.
"""
