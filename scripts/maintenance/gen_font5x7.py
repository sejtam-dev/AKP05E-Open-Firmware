# the table is indexed by (character - 0x20) up to 'Z' (0x5a); characters without a glyph stay blank
FIRST, LAST = 0x20, 0x5A


def row_bits(row):
    value = 0
    for col, ch in enumerate(row):
        if ch == "#":
            value |= 1 << (4 - col)         # bit 4 = leftmost pixel
    return value


def main():
    for key, rows in GLYPHS.items():
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), key
    if "--show" in sys.argv:
        for key, rows in GLYPHS.items():
            print("'%s'" % key)
            print("\n".join(r.replace(".", " ") for r in rows))
        return
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out = ["/* Generated by scripts/maintenance/gen_font5x7.py - do not edit. 5x7 pixel font, one byte per row,",
           " * bit 4 = leftmost pixel, indexed by (character - 0x20); lower case is drawn as upper case. */",
           "#ifndef FONT5X7_H", "#define FONT5X7_H", "",
           "#define FONT_FIRST 0x%02x" % FIRST, "#define FONT_LAST  0x%02x" % LAST, "",
           "static const unsigned char font5x7[FONT_LAST - FONT_FIRST + 1][7] = {"]
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = GLYPHS.get(ch, GLYPHS[" "])
        out.append("    { %s },   /* '%s' */" % (", ".join("0x%02x" % row_bits(r) for r in rows),
                                                 ch if ch != "\\" else "backslash"))
    out += ["};", "", "#endif /* FONT5X7_H */", ""]
    path = os.path.join(root, "firmware", "app", "font5x7.h")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
