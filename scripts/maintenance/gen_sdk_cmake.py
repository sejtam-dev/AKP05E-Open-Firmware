#!/usr/bin/env python3
"""Generate cmake/sdk_sources.cmake from what the SDK's own SCons build really does.

Input
  build/logs/scons_full_verbose.log   output of `scons --verbose` for a full build of the chosen defconfig
                                   (regenerate: scons -c ; scons --verbose > build/logs/scons_full_verbose.log)

Output
  cmake/sdk_sources.cmake          SDK_C_FLAGS, SDK_DEFINITIONS, SDK_INCLUDE_DIRS, SDK_SOURCES (relative to ${SDK_DIR})
                                   plus per-file extra include directories (SCons LOCAL_CPPPATH groups)

The application directory of the SDK (application/rt-thread/<app>) is left out: this project builds its own
application (firmware/app/).
"""
import collections
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))   # repository root
LOG = os.path.join(ROOT, "build", "logs", "scons_full_verbose.log")
OUT = os.path.join(ROOT, "cmake", "sdk_sources.cmake")
APP_PREFIX = "application/rt-thread/"


def norm(p):
    return p.replace("\\", "/")


def parse_commands():
    cmds = []
    for line in open(LOG, encoding="utf-8", errors="replace").read().replace("\r", "").split("\n"):
        if "riscv64-unknown-elf-gcc" not in line or " -o " not in line or " -c " not in line:
            continue
        toks = line.split()
        obj = toks[toks.index("-o") + 1]
        src = [t for t in toks if re.search(r"\.(c|S)$", t)][-1]
        flags = [t for t in toks if t.startswith("-") and not t.startswith(("-I", "-D")) and t != "-o"]
        defs = [t for t in toks if t.startswith("-D")]
        incs = [norm(t[2:]) for t in toks if t.startswith("-I")]
        cmds.append(dict(obj=obj, src=norm(src), flags=flags, defs=defs, incs=incs))
    return cmds


def main():
    # The project has its own application and its own CherryUSB HID setup (firmware/app/usb_hid.c): leave out the SDK demos
    skip = ("cherryusb/demo/",)
    cmds = [c for c in parse_commands()
            if not c["src"].startswith(APP_PREFIX) and not any(s in c["src"] for s in skip)]
    if not cmds:
        sys.exit("no compile commands in " + LOG)
    # keep the link order of the SCons build (decides what sits at the start of .text, i.e. the entry point)
    link_order = {}
    for line in open(LOG, encoding="utf-8", errors="replace").read().replace(chr(13), "").split(chr(10)):
        if " -o " in line and ".elf" in line and "-Wl,-Map" in line:
            for i, t in enumerate(line.split()):
                if t.endswith(".o"):
                    link_order[norm(t)] = i
    cmds.sort(key=lambda c: link_order.get(norm(c["obj"]), 1 << 30))
    c_cmds = [c for c in cmds if c["src"].endswith(".c")]

    base_incs = collections.Counter(tuple(c["incs"]) for c in c_cmds).most_common(1)[0][0]
    base_defs = collections.Counter(tuple(c["defs"]) for c in c_cmds).most_common(1)[0][0]
    flags = []
    for t in c_cmds[0]["flags"]:
        if t not in ("-c",) and t not in flags:
            flags.append(t)

    extra = {}
    for c in cmds:
        add = [i for i in c["incs"] if i not in base_incs]
        if add:
            extra[c["src"]] = add

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# GENERATED by scripts/maintenance/gen_sdk_cmake.py from build/logs/scons_full_verbose.log - do not edit by hand.\n\n")
        f.write("set(SDK_C_FLAGS\n" + "".join("    %s\n" % x for x in flags) + ")\n\n")
        f.write("set(SDK_DEFINITIONS\n" + "".join("    %s\n" % x for x in base_defs) + ")\n\n")
        f.write("set(SDK_INCLUDE_DIRS\n")
        for x in base_incs:
            f.write("    ${SDK_DIR}\n" if x == "." else "    ${SDK_DIR}/%s\n" % x)
        f.write(")\n\nset(SDK_SOURCES\n")
        for c in cmds:
            f.write("    ${SDK_DIR}/%s\n" % c["src"])
        f.write(")\n\n# Extra include directories of single SCons groups (LOCAL_CPPPATH), appended after the common ones.\n")
        f.write("set(SDK_EXTRA_INCLUDES_BY_FILE\n")
        for src, add in sorted(extra.items()):
            f.write("    \"${SDK_DIR}/%s|%s\"\n" % (src, "|".join("-I${SDK_DIR}/" + a if a != "." else "-I${SDK_DIR}" for a in add)))
        f.write(")\n")
    print("flags %d, defs %d, include dirs %d, sources %d (per-file extra includes: %d) -> %s"
          % (len(flags), len(base_defs), len(base_incs), len(cmds), len(extra), OUT))


if __name__ == "__main__":
    main()
